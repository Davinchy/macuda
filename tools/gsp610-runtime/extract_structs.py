#!/usr/bin/env python3
""": extract typedef blocks VERBATIM from the pinned NVIDIA trees into a self-contained header.

Some firmware-facing structures (GspSystemInfo and its BUSINFO / ACPI_METHOD_DATA / GSP_VF_INFO /
GSP_PCIE_CONFIG_REG dependencies) live behind NVIDIA's NVOC port layer, so a probe cannot include their
headers standalone (nvassert.h demands a port header). The audit left GspSystemInfo's 610 offsets
unresolved for exactly this reason, with the resolution step "a 610-only assertion TU".

This tool resolves it without weakening anything: it copies the typedef text byte-for-byte out of the
hash-verified pinned tree (fetch_inputs.sh verifies the archive SHA-256), records the source file and line
for every block, and emits a header the assertion TU compiles against nvtypes.h / nvstatus.h / the ctrl
headers (which ARE includable). Nothing is retyped by hand, so the assertion compares the driver's
declarations against NVIDIA's actual text, not a transcription.

    python3 tools/gsp610-runtime/extract_structs.py <tree-root> <out-header>

Fails loudly if a block is missing or ambiguous. Deterministic: same tree -> same bytes.
"""
import re
import sys
import pathlib

# (relative file, typedef name) in dependency order. Every block is copied verbatim.
WANTED = [
    # BUSINFO: the generated NVOC header carries the same definition chipset.h includes.
    ("src/nvidia/generated/g_chipset_nvoc.h", "BUSINFO"),
    ("src/nvidia/inc/kernel/gpu/gpu_acpi_data.h", "DOD_METHOD_DATA"),
    ("src/nvidia/inc/kernel/gpu/gpu_acpi_data.h", "JT_METHOD_DATA"),
    ("src/nvidia/inc/kernel/gpu/gpu_acpi_data.h", "MUX_METHOD_DATA_ELEMENT"),
    ("src/nvidia/inc/kernel/gpu/gpu_acpi_data.h", "MUX_METHOD_DATA"),
    ("src/nvidia/inc/kernel/gpu/gpu_acpi_data.h", "CAPS_METHOD_DATA"),
    ("src/nvidia/inc/kernel/gpu/gpu_acpi_data.h", "ACPI_METHOD_DATA"),
    ("src/nvidia/inc/kernel/gpu/gsp/gsp_static_config.h", "GSP_VF_INFO"),
    ("src/nvidia/inc/kernel/gpu/gsp/gsp_static_config.h", "GSP_PCIE_CONFIG_REG"),
    ("src/nvidia/inc/kernel/gpu/gsp/gsp_static_config.h", "GspSystemInfo"),
    # the 610 host-request payloads and the falcon bootloader descriptor they carry
    ("src/nvidia/arch/nvalloc/common/inc/flcnifcmn.h", "RM_FLCN_U64"),
    ("src/nvidia/arch/nvalloc/common/inc/rmflcnbl.h", "RM_FLCN_BL_DMEM_DESC"),
    ("src/nvidia/arch/nvalloc/common/inc/rmflcnbl.h", "RM_FLCN_BL_IMG_HEADER"),
    ("src/nvidia/arch/nvalloc/common/inc/rmflcnbl.h", "RM_FLCN_BL_DESC"),
    ("src/nvidia/arch/nvalloc/common/inc/rmgspseq.h", "GspLoadExecGenericBootloaderParams"),
    ("src/nvidia/arch/nvalloc/common/inc/rmgspseq.h", "GspLoadExecHsBinaryParams"),
    # the 610 queue element (MCTP/NVDM framing); its header pulls the CC/port layer, so extract it verbatim too
    ("src/nvidia/inc/kernel/gpu/gsp/message_queue_priv.h", "GSP_MSG_QUEUE_ELEMENT"),
]


def extract(text: str, name: str, where: str) -> tuple[str, int]:
    """The typedef block ending in '} NAME;' (or '} NAME, *PNAME;'), from its column-0 'typedef'.
    A one-line alias typedef ('typedef X NAME;') is copied as that single line."""
    alias = [m for m in re.finditer(r"^typedef\s+[^;{}]+\b" + re.escape(name) + r"\s*;", text, re.M)]
    if len(alias) == 1:
        m = alias[0]
        return m.group(0), text.count("\n", 0, m.start()) + 1
    ends = [m for m in re.finditer(r"^\}\s*" + re.escape(name) + r"\s*(,[^;]*)?;", text, re.M)]
    if len(ends) != 1:
        raise SystemExit(f"{where}: typedef {name}: found {len(ends)} definitions, want exactly 1")
    end = ends[0]
    starts = [m for m in re.finditer(r"^typedef\b", text[: end.start()], re.M)]
    if not starts:
        raise SystemExit(f"{where}: typedef {name}: no 'typedef' before the closing brace")
    start = starts[-1].start()
    block = text[start : end.end()]
    # a nested 'typedef' would mean the backward scan grabbed two blocks; refuse rather than emit garbage
    if len(re.findall(r"^typedef\b", block, re.M)) != 1:
        raise SystemExit(f"{where}: typedef {name}: block is not a single typedef")
    line = text.count("\n", 0, start) + 1
    return block, line


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    tree, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    if not (tree / "src").is_dir():
        raise SystemExit(f"no pinned tree at {tree} (run tools/gsp610-runtime/fetch_inputs.sh)")
    parts = [
        "// GENERATED by tools/gsp610-runtime/extract_structs.py - do not edit.",
        "// Typedef blocks copied VERBATIM from the pinned, hash-verified NVIDIA tree; source cited per block.",
        "#ifndef TINYNV_EXTRACTED_STRUCTS_H",
        "#define TINYNV_EXTRACTED_STRUCTS_H",
        '#include "nvtypes.h"',
        '#include "nvstatus.h"',
        '#include "ctrl/ctrl0073/ctrl0073system.h"',
        "",
    ]
    for rel, name in WANTED:
        text = (tree / rel).read_text()
        block, line = extract(text, name, rel)
        parts.append(f"// --- {name}: {rel}:{line} (verbatim) ---")
        parts.append(block)
        parts.append("")
    parts.append("#endif")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts) + "\n")
    print(f"extracted {len(WANTED)} typedefs -> {out}")


if __name__ == "__main__":
    main()